    private static final Sprite[] CACHE = new Sprite[ART.length];

    public static Sprite icon(int weaponId) {
        Sprite s = CACHE[weaponId];
        if (s == null) {
            s = Sprite.parseFixed(ART[weaponId], 16, 16);
            CACHE[weaponId] = s;
        }
        return s;
    }

    public static int count() {
        return ART.length;
    }

