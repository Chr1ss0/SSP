    private static final HashMap<Character, Glyph> GLYPHS = new HashMap<Character, Glyph>();

    private static void g(char ch, String... rows) {
        int w = 0;
        for (String r : rows) w = Math.max(w, r.length());
        int[] bits = new int[rows.length];
        for (int y = 0; y < rows.length; y++) {
            String r = rows[y];
            int b = 0;
            for (int x = 0; x < r.length(); x++) if (r.charAt(x) == '#') b |= 1 << (w - 1 - x);
            bits[y] = b;
        }
        GLYPHS.put(ch, new Glyph(w, bits));
    }

