    private static Glyph glyph(char c) {
        Glyph gl = GLYPHS.get(c);
        if (gl == null) gl = GLYPHS.get('?');
        return gl;
    }

    public static int charWidth(char c) {
        return glyph(c).width;
    }

    /** Width in pixels of a single-line string (no trailing spacing). */
    public static int width(String s, int scale) {
        int best = 0, cur = 0;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == '\n') { best = Math.max(best, cur); cur = 0; continue; }
            if (cur > 0) cur += 1;
            cur += glyph(c).width;
        }
        return Math.max(best, cur) * scale;
    }

    /** Draws text; returns x position after the last glyph. Supports '\n'. */
    public static int draw(Gfx g, String s, int x, int y, int color, int scale) {
        int cx = x, cy = y;
        boolean first = true;
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            if (c == '\n') { cx = x; cy += LINE * scale; first = true; continue; }
            if (!first) cx += scale;
            first = false;
            Glyph gl = glyph(c);
            for (int ry = 0; ry < gl.rows.length; ry++) {
                int bits = gl.rows[ry];
                if (bits == 0) continue;
                for (int rx = 0; rx < gl.width; rx++) {
                    if ((bits & (1 << (gl.width - 1 - rx))) != 0) {
                        if (scale == 1) g.pset(cx + rx, cy + ry, color);
                        else g.fill(cx + rx * scale, cy + ry * scale, scale, scale, color);
                    }
                }
            }
            cx += gl.width * scale;
        }
        return cx;
    }

    /** Greedy word wrap. Respects explicit '\n'. */
    public static List<String> wrap(String text, int maxWidth) {
        List<String> out = new ArrayList<String>();
        String[] paragraphs = text.split("\n", -1);
        for (String p : paragraphs) {
            String[] words = p.split(" ");
            StringBuilder line = new StringBuilder();
            for (String word : words) {
                if (word.length() == 0) continue;
                String cand = line.length() == 0 ? word : line + " " + word;
                if (width(cand, 1) <= maxWidth || line.length() == 0) {
                    if (line.length() == 0 && width(word, 1) > maxWidth) {
                        // hard-break overly long words
                        String rest = word;
                        while (width(rest, 1) > maxWidth) {
                            int n = rest.length() - 1;
                            while (n > 1 && width(rest.substring(0, n) + "-", 1) > maxWidth) n--;
                            out.add(rest.substring(0, n) + "-");
                            rest = rest.substring(n);
                        }
                        line.setLength(0);
                        line.append(rest);
                    } else {
                        line.setLength(0);
                        line.append(cand);
                    }
                } else {
                    out.add(line.toString());
                    line.setLength(0);
                    line.append(word);
                }
            }
            out.add(line.toString());
        }
        return out;
    }

